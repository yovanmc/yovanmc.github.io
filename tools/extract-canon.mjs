function fail(msg) {
  console.error("extract-canon: " + msg);
  process.exit(1);
}

// Windows checkouts may be CRLF; the transform is defined over LF content.
function readLf(path) {
  return readFileSync(path, "utf8").replace(/\r\n/g, "\n");
}

function extractStationBody() {
  const html = readLf(STATION_LAB);
  const m = html.match(/<script>\n([\s\S]*?)<\/script>/);
  if (!m) fail("no <script> block found in station-glass.html");
  const body = m[1];
  const cut = body.indexOf("document.getElementById('station')");
  if (cut < 0) fail("trailing DOM-write anchor not found in station-glass.html");
  return body.slice(0, cut).replace(/\s+$/, "");
}

function buildModule(body) {
  return `// @ts-nocheck
/* eslint-disable */
// GENERATED by tools/extract-canon.mjs from docs/battle-prototypes/station-glass.html
// (station v1 canon, LOCKED 2026-07-27 — spec docs/superpowers/specs/2026-07-27-station-glass-design.md).
// DO NOT EDIT. The canon body below this header is verbatim (BUILDING.md §8).
// Regenerate: node tools/extract-canon.mjs   Verify: npm run verify:canon
export function buildStationCanon(idSuffix = "") {
${body}
if (idSuffix) out = out.replace(/fcL|skL|wtL/g, (t) => t + idSuffix);
return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="-510 -510 1020 1020" width="100%" height="100%">' + out + "</svg>";
}
`;
}

// Normalize a builder body for the lab-copy drift diff: strip blank lines and
// trailing whitespace so wrapper-shape differences (function vs top-level) don't
// mask or fake real drift.
function normalize(s) {
  return s
    .split("\n")
    .map((l) => l.replace(/\s+$/, ""))
    .filter((l) => l !== "")
    .join("\n");
}

function extractDiveStationBody() {
  const html = readLf(DIVE_LAB);
  const m = html.match(/function buildStationString\(\)\{\n([\s\S]*?)\nreturn out;\n\}/);
  if (!m) fail("buildStationString not found in dive-intro.html");
  return m[1];
}

function extractTimelineBody() {
  const html = readLf(DIVE_LAB);
  const m = html.match(/<script id="pure">\n([\s\S]*?)<\/script>/);
  if (!m) fail('no <script id="pure"> block found in dive-intro.html');
  return m[1].replace(/\s+$/, "");
}

