// Two-anchor slice; the cut lands at the START of the line holding endAnchor.
function sliceBetween(html, startAnchor, endAnchor, name) {
  const a = html.indexOf(startAnchor);
  if (a < 0) fail("start anchor `" + startAnchor + "` not found in " + name);
  let b = html.indexOf(endAnchor, a);
  if (b < 0) fail("end anchor `" + endAnchor + "` not found in " + name);
  b = html.lastIndexOf("\n", b) + 1;
  return html.slice(a, b).replace(/\s+$/, "");
}

function battleHeader(source, note) {
  return `// @ts-nocheck
/* eslint-disable */
// GENERATED by tools/extract-canon.mjs from docs/battle-prototypes/${source}
// (M5 battle canon — plan docs/superpowers/specs/2026-07-28-be1-battle-engine-plan.md).
// DO NOT EDIT. The slice below this header is verbatim (BUILDING.md §9).
// ${note}
// Regenerate: node tools/extract-canon.mjs   Verify: npm run verify:canon
`;
}

